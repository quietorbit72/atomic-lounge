// Vintage Chonk plugin: write the panel's factory bank (js/factory.js of the panel) as .mfp images
// into plugin/generated/factory_presets.h, so the plugin can offer them as host programs without the
// editor open. The panel builds the same bank at run time; the order (and so the program numbers) match.
//   node plugin/tools/gen_factory.mjs            (writes the header)
//   node plugin/tools/gen_factory.mjs --check    (exit 1 if the header is stale)
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
// the panel: panel (development repository) or panel/ (public source tree)
const WWW = path.join(fs.existsSync(path.join(ROOT, 'panel/index.html')) ? path.join(ROOT, 'panel') : path.join(ROOT, 'panel'), 'js');
const Core = require(path.join(WWW, 'mf_core.js'));
const M = require(path.join(WWW, 'panel_model.js'));
const F = require(path.join(WWW, 'factory.js'));
const OUT = path.join(ROOT, 'plugin/generated/factory_presets.h');

const bank = F.build(Core, M);
let s = '// SPDX-License-Identifier: AGPL-3.0-only\n';
s += '// GENERATED by plugin/tools/gen_factory.mjs from the panel (js/factory.js). Do not edit.\n';
s += '#pragma once\n#include <cstdint>\n#include <cstddef>\n\nnamespace mfm1_factory {\n';
s += `constexpr int count = ${bank.length};\nconstexpr size_t size = ${Core.MFP.SIZE};\n`;
s += 'inline const char* const names[count] = {\n';
for (const p of bank) s += `    ${JSON.stringify(p.name)},\n`;
s += '};\ninline const uint8_t images[count][size] = {\n';
for (const p of bank) {
  const img = Core.mfpWrite(p);
  if (img.length !== Core.MFP.SIZE) throw new Error(`${p.name}: ${img.length} bytes`);
  s += '    {';
  for (let i = 0; i < img.length; i++) s += (i % 24 === 0 ? '\n        ' : '') + `${img[i]},`;
  s += '\n    },\n';
}
s += '};\n}\n';

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== s) { console.log('plugin/generated/factory_presets.h is stale: run node plugin/tools/gen_factory.mjs'); process.exit(1); }
  console.log(`factory_presets.h current (${bank.length} presets)`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, s);
  console.log(`wrote ${OUT}: ${bank.length} presets of ${Core.MFP.SIZE} B`);
}
