# Vintage Chonk Android UI: copy the converter core and the mapping profiles into the WebView page.
#   editor/src/mf_core.js                -> panel/js/mf_core.js   (verbatim copy)
#   tools/preset_converter/maps/*.json   -> panel/js/mf_profiles.js (sorted by file name,
#                                           as tools/build_editor.py and convert.py use them)
#   python -I tools/sync_ui_core.py [--check]
# --check exits 1 when the copies are out of date (used by tests/test_panel.mjs).
import argparse
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
CORE_SRC = os.path.join(ROOT, "editor", "src", "mf_core.js")
MAPS = os.path.join(ROOT, "tools", "preset_converter", "maps")
WWW_JS = os.path.join(ROOT, "panel", "js")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def profiles_js():
    items = []
    for fn in sorted(os.listdir(MAPS)):
        if fn.endswith(".json"):
            items.append({"name": fn, "profile": json.loads(read(os.path.join(MAPS, fn)))})
    text = json.dumps(items, ensure_ascii=True, separators=(",", ":"))
    return ("// SPDX-License-Identifier: AGPL-3.0-only\n"
            "// Generated by tools/sync_ui_core.py from tools/preset_converter/maps/*.json. Do not edit.\n"
            "'use strict';\n"
            "(function (root) {\n"
            f"  const PROFILES = {text};\n"
            "  if (typeof module === 'object' && module.exports) module.exports = PROFILES;\n"
            "  else root.MF_PROFILES = PROFILES;\n"
            "})(typeof self !== 'undefined' ? self : this);\n"), len(items)


def wanted():
    prof, n = profiles_js()
    return {os.path.join(WWW_JS, "mf_core.js"): read(CORE_SRC),
            os.path.join(WWW_JS, "mf_profiles.js"): prof}, n


def main(argv=None):
    ap = argparse.ArgumentParser(description="Sync the converter core into the Android UI")
    ap.add_argument("--check", action="store_true", help="only report whether the copies are current")
    a = ap.parse_args(argv)
    files, n = wanted()
    stale = [p for p, t in files.items() if not os.path.exists(p) or read(p) != t]
    if a.check:
        for p in stale:
            print(f"stale: {os.path.relpath(p, ROOT)}")
        return 1 if stale else 0
    os.makedirs(WWW_JS, exist_ok=True)
    for p, t in files.items():
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(t)
    print(f"synced mf_core.js and mf_profiles.js ({n} mapping profiles) into {os.path.relpath(WWW_JS, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
