/* SPDX-License-Identifier: AGPL-3.0-only
 * Vintage Chonk: emit the MFE lookup tables and wavetables as const C data for the FM1.
 *
 * The device must not build its tables at boot (192 KB of RAM, soft double maths). This host
 * tool includes dsp/mfe_tables.c unchanged, runs mfe_init_tables() with the host's libm, and
 * writes one C file that replaces dsp/mfe_tables.c in the device build:
 *   - every table as `const` data (the linker puts it in Flash .rodata),
 *   - mfe_init_tables() as a no-op, mfe_wavetable_name(),
 *   - the integer accessors, copied verbatim from dsp/mfe_tables.c (from the line
 *     "integer accessors used by the audio path" to the end), so they never drift.
 *
 * Build and run (from the repository root):
 *   gcc -O2 -Idsp/include -Idsp tools/gen_tables/gen_tables.c -lm -o build/gen_tables.exe
 *   build/gen_tables.exe dsp/mfe_tables.c build/generated/mfe_tables_const.c
 *
 * The output declares the tables `const` while mfe_internal.h declares mfe_sine_tab / mfe_wt
 * without const. That is only safe because nothing writes them once mfe_init_tables is a no-op;
 * the clean fix is the small dsp change in docs/FM1_FIRMWARE_BUILD_PLAN.md (MFE_CONST_TABLES). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "mfe_tables.c"

static const char MARKER[] = "integer accessors used by the audio path";

static void emit_i16(FILE *o, const char *decl, const int16_t *v, size_t n)
{
    fprintf(o, "%s = {", decl);
    for (size_t i = 0; i < n; i++) fprintf(o, "%s%d", !i ? "\n  " : i % 16 ? "," : ",\n  ", v[i]);
    fprintf(o, "\n};\n");
}
static void emit_u32(FILE *o, const char *decl, const uint32_t *v, size_t n)
{
    fprintf(o, "%s = {", decl);
    for (size_t i = 0; i < n; i++) fprintf(o, "%s%luu", !i ? "\n  " : i % 8 ? "," : ",\n  ", (unsigned long)v[i]);
    fprintf(o, "\n};\n");
}
static void emit_i32(FILE *o, const char *decl, const int32_t *v, size_t n)
{
    fprintf(o, "%s = {", decl);
    for (size_t i = 0; i < n; i++) fprintf(o, "%s%ld", !i ? "\n  " : i % 8 ? "," : ",\n  ", (long)v[i]);
    fprintf(o, "\n};\n");
}

int main(int argc, char **argv)
{
    if (argc != 3) { fprintf(stderr, "usage: gen_tables <dsp/mfe_tables.c> <out.c>\n"); return 2; }
    FILE *src = fopen(argv[1], "rb");
    if (!src) { perror(argv[1]); return 1; }
    static char text[1 << 20];
    size_t len = fread(text, 1, sizeof text - 1, src);
    fclose(src);
    text[len] = 0;
    char *tail = strstr(text, MARKER);
    if (!tail) { fprintf(stderr, "marker \"%s\" not found in %s\n", MARKER, argv[1]); return 1; }
    while (tail > text && tail[-1] != '\n') tail--;          /* start of the marker's line */

    mfe_init_tables();
    FILE *o = fopen(argv[2], "wb");
    if (!o) { perror(argv[2]); return 1; }
    fprintf(o, "/* GENERATED by tools/gen_tables/gen_tables.c from dsp/mfe_tables.c: do not edit.\n"
               " * Device replacement for dsp/mfe_tables.c: const tables in Flash, no init maths. */\n"
               "#define mfe_sine_tab mfe_sine_tab_decl_unused\n"
               "#define mfe_wt mfe_wt_decl_unused\n"
               "#include \"mfe_internal.h\"\n"
               "#undef mfe_sine_tab\n#undef mfe_wt\n\n");
    emit_i16(o, "const int16_t mfe_sine_tab[1025]", mfe_sine_tab, 1025);
    emit_u32(o, "static const uint32_t inc_tab[193]", inc_tab, 193);
    emit_i32(o, "static const int32_t g_tab[545]", g_tab, 545);
    emit_u32(o, "static const uint32_t ticks_tab[257]", ticks_tab, 257);
    emit_i32(o, "static const int32_t coef_tab[257]", coef_tab, 257);
    emit_u32(o, "static const uint32_t lfo_tab[257]", lfo_tab, 257);
    emit_i16(o, "static const int16_t clip_tab[1025]", clip_tab, 1025);
    fprintf(o, "#pragma GCC diagnostic ignored \"-Wmissing-braces\"\n");   /* flat initialiser */
    fprintf(o, "#ifndef MFE_WT_SECTION\n#define MFE_WT_SECTION\n#endif\n");
    {
        char decl[160];
        snprintf(decl, sizeof decl, "MFE_WT_SECTION const int16_t mfe_wt[%d][%d][%d][%d]",
                 MFE_WT_COUNT, MFE_WT_FRAMES, MFE_WT_LEVELS, MFE_WT_FRAME);
        emit_i16(o, decl, &mfe_wt[0][0][0][0], sizeof mfe_wt / sizeof mfe_wt[0][0][0][0]);
    }
    fprintf(o, "\nstatic const char *const WT_NAMES[MFE_WT_COUNT] = {");
    for (unsigned t = 0; t < MFE_WT_COUNT; t++) fprintf(o, "%s\"%s\"", t ? ", " : "", mfe_wavetable_name(t));
    fprintf(o, "};\nconst char *mfe_wavetable_name(unsigned t) { return t < MFE_WT_COUNT ? WT_NAMES[t] : \"?\"; }\n"
               "void mfe_init_tables(void) { }\n\n");
    fputs(tail, o);
    fclose(o);
    fprintf(stderr, "gen_tables: wrote %s (wavetables %lu bytes, other tables %lu bytes)\n", argv[2],
            (unsigned long)sizeof mfe_wt,
            (unsigned long)(sizeof mfe_sine_tab + sizeof inc_tab + sizeof g_tab + sizeof ticks_tab +
                            sizeof coef_tab + sizeof lfo_tab + sizeof clip_tab));
    return 0;
}
